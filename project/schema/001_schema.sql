-- Le schéma des prêts du réseau de Valmorin, traduit du MCD et du dictionnaire de données.
-- Chaque id est généré par défaut : les données de l'ancien logiciel arrivent avec les leurs.

create table site (
  id    integer generated by default as identity primary key,
  nom   varchar(30) not null,
  ville varchar(30) not null
);

create table adherent (
  id               integer generated by default as identity primary key,
  numero_carte     varchar(9)  not null unique,
  nom              varchar(30) not null,
  prenom           varchar(30) not null,
  email            varchar(60) not null unique,
  telephone        varchar(10),
  date_inscription date        not null,
  site_id          integer     not null references site (id)
);

create table auteur (
  id     integer generated by default as identity primary key,
  nom    varchar(30) not null,
  prenom varchar(30) not null
);

create table ouvrage (
  id      integer generated by default as identity primary key,
  isbn    char(13) unique,
  titre   varchar(80) not null,
  annee   smallint    not null,
  editeur varchar(30)
);

-- L'association « écrit par » (n,n) : une ligne par couple (ouvrage, auteur).
create table ouvrage_auteur (
  ouvrage_id integer not null references ouvrage (id),
  auteur_id  integer not null references auteur (id),
  primary key (ouvrage_id, auteur_id)
);

create table exemplaire (
  id         integer generated by default as identity primary key,
  ouvrage_id integer     not null references ouvrage (id),
  site_id    integer     not null references site (id),
  code_barre varchar(10) not null unique,
  etat       varchar(6)  not null check (etat in ('neuf', 'bon', 'abime', 'retire'))
);

-- On ne supprime pas un adhérent qui a un historique de prêts.
create table emprunt (
  id                 integer generated by default as identity primary key,
  exemplaire_id      integer not null references exemplaire (id),
  adherent_id        integer not null references adherent (id) on delete restrict,
  date_emprunt       date    not null,
  date_retour_prevue date    not null,
  date_retour        date,
  check (date_retour_prevue > date_emprunt),
  check (date_retour >= date_emprunt)
);
