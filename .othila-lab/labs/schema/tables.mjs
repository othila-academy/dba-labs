export const checks = [
  {
    id: 'tables-colonnes',
    label: 'les 7 tables du dictionnaire existent, avec leurs colonnes',
    run: () =>
      withPg(async (client) => {
        const missing = missingFrom(await columnsOf(client));
        assert(
          missing.length === 0,
          `Attendu : les tables et colonnes du dictionnaire. Constaté : il manque ${missing.join(', ')}. Les noms sont un contrat : la liste complète, clés étrangères comprises, est dans MCD.md (« Les colonnes de chaque table »).`
        );
      })
  },
  {
    id: 'cles-primaires',
    label: 'chaque table a une clé primaire ; celle de ouvrage_auteur porte sur ses deux colonnes',
    run: () =>
      withPg(async (client) => {
        const { rows } = await client.query(
          `select c.relname as tbl, array_agg(a.attname::text order by a.attname) as cols
           from pg_constraint k
           join pg_class c on c.oid = k.conrelid
           join pg_attribute a on a.attrelid = k.conrelid and a.attnum = any (k.conkey)
           where k.contype = 'p' and c.relnamespace = 'public'::regnamespace
           group by c.relname`
        );
        const keys = Object.fromEntries(rows.map((r) => [r.tbl, r.cols.join(', ')]));
        const missing = TABLE_NAMES.filter((t) => !keys[t]);
        assert(missing.length === 0, `Attendu : une clé primaire sur chaque table. Constaté : aucune sur ${missing.join(', ')}.`);
        for (const t of TABLE_NAMES.filter((name) => name !== 'ouvrage_auteur')) {
          assert(keys[t] === 'id', `Attendu : la clé primaire de ${t} sur id. Constaté : sur (${keys[t]}).`);
        }
        assert(
          keys.ouvrage_auteur === 'auteur_id, ouvrage_id',
          `Attendu : la clé primaire de ouvrage_auteur sur ses deux colonnes. Constaté : sur (${keys.ouvrage_auteur}). Qu'est-ce qui identifie une ligne de cette association ?`
        );
      })
  },
  {
    id: 'id-identite',
    label: 'chaque id est un entier généré par défaut (generated by default as identity)',
    run: () =>
      withPg(async (client) => {
        const columns = await requireDictionary(client);
        const wrong = [];
        for (const t of TABLE_NAMES.filter((name) => name !== 'ouvrage_auteur')) {
          const id = columns[t].get('id');
          if (id.identity && id.generation === 'BY DEFAULT') continue;
          wrong.push(`${t}.id ${id.identity ? 'generated always' : id.defaut ? `par défaut ${id.defaut}` : 'non généré'}`);
        }
        assert(
          wrong.length === 0,
          `Attendu : des id generated by default as identity (infra/seed/CONTRAT.md). Constaté : ${wrong.join(', ')}. Les données arrivent avec leurs propres id : la colonne doit les accepter.`
        );
      })
  }
];

