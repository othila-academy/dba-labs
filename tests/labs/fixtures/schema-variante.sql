-- Un schéma différent de la solution, mais conforme au dictionnaire et aux règles : les checks du lab schema l'acceptent.
-- Type énuméré, text partout, isbn en bigint, index uniques au lieu de contraintes, règle des dates par déclencheur,
-- clé composite dans l'autre ordre, un seul emprunt en cours par exemplaire.
create type etat_exemplaire as enum ('neuf', 'bon', 'abime', 'retire');

create table site (
  id bigint generated by default as identity,
  nom text not null,
  ville text not null,
  constraint site_pk primary key (id)
);

create table adherent (
  id bigint generated by default as identity primary key,
  numero_carte text not null,
  nom text not null,
  prenom text not null,
  email text not null,
  telephone text,
  date_inscription date not null,
  site_id bigint not null,
  constraint adherent_site_fk foreign key (site_id) references site (id)
);
create unique index adherent_carte_uq on adherent (numero_carte);
create unique index adherent_email_uq on adherent (lower(email));

create table auteur (id bigint generated by default as identity primary key, nom text not null, prenom text not null);

create table ouvrage (
  id bigint generated by default as identity primary key,
  isbn bigint,
  titre text not null,
  annee integer not null,
  editeur text
);
create unique index ouvrage_isbn_uq on ouvrage (isbn) where isbn is not null;

create table ouvrage_auteur (
  auteur_id bigint not null references auteur,
  ouvrage_id bigint not null references ouvrage,
  constraint ouvrage_auteur_pk primary key (auteur_id, ouvrage_id)
);

create table exemplaire (
  id bigint generated by default as identity primary key,
  ouvrage_id bigint not null references ouvrage,
  site_id bigint not null references site,
  code_barre text not null unique,
  etat etat_exemplaire not null
);

create table emprunt (
  id bigint generated by default as identity primary key,
  exemplaire_id bigint not null references exemplaire,
  adherent_id bigint not null references adherent,
  date_emprunt date not null,
  date_retour_prevue date not null,
  date_retour date
);
create unique index emprunt_un_en_cours on emprunt (exemplaire_id) where date_retour is null;

create function emprunt_dates() returns trigger language plpgsql as $$
begin
  if new.date_retour_prevue <= new.date_emprunt then raise exception 'retour prévu avant l''emprunt'; end if;
  if new.date_retour < new.date_emprunt then raise exception 'retour avant l''emprunt'; end if;
  return new;
end $$;
create trigger emprunt_dates before insert or update on emprunt for each row execute function emprunt_dates();
