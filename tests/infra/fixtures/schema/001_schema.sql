-- Schéma de test des seeds : les noms du dictionnaire, des types simples, aucune règle métier.
create table site (id integer generated by default as identity primary key, nom text, ville text);
create table adherent (id integer generated by default as identity primary key, numero_carte text, nom text, prenom text,
  email text, telephone text, date_inscription date, site_id integer);
create table auteur (id integer generated by default as identity primary key, nom text, prenom text);
create table ouvrage (id integer generated by default as identity primary key, isbn text, titre text, annee integer, editeur text);
create table ouvrage_auteur (ouvrage_id integer, auteur_id integer, primary key (ouvrage_id, auteur_id));
create table exemplaire (id integer generated by default as identity primary key, ouvrage_id integer, site_id integer,
  code_barre text, etat text);
create table emprunt (id integer generated by default as identity primary key, exemplaire_id integer, adherent_id integer,
  date_emprunt date, date_retour_prevue date, date_retour date);
